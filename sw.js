/* Type-R 198X — service worker (PLATFORM pass, 2026-11): installable, offline-capable shell.
 *
 * Versioned by the shell token: tools/bump-version.sh rewrites SW_VERSION and every ?v= inside PRECACHE below with the
 * same URL rule as the HTML pages (assets/opt URLs take the ART token, everything else the shell token). A new token is
 * a new service worker: it installs beside the running one, the page shows "NEW VERSION READY" (12-access.js) and the
 * swap happens only when the player asks (postMessage {type: "SKIP_WAITING"}, from the menu, never during play); the
 * previous release's caches are deleted on activate. Nothing here calls skipWaiting or clients.claim on its own.
 *
 * Strategies (same-origin GET only; other methods, /api/ and cross-origin requests are never intercepted):
 *   navigations      network-first, cache fallback (the page as last stored, else index.html): online the shell always
 *                    revalidates (audit G025), offline it opens from the cache
 *   assets/opt/**    cache-first in a release-independent cache (the URLs carry the ART token and are immutable). A
 *                    media range request is answered from a cached full copy (a 206 cut from it); an open-ended
 *                    "bytes=0-" request streams the network body to the player while the same bytes are stored (one
 *                    download, no buffering delay); any other range passes through. The cache is capped at
 *                    OPT_CACHE_MAX_BYTES, oldest entries out, audited every OPT_EVICT_EVERY stores.
 *   everything else  the precached shell copy when there is one (a versioned URL never changes under one token), else
 *                    stale-while-revalidate in a per-release runtime cache
 *
 * PRECACHE is generated by tools/gen-sw-precache.mjs from index.html (every local <script> / <link> it references, the
 * secondary pages, the web manifest, assets/fonts, assets/ui). Install adds the entries one by one and swallows every
 * failure, so a stale or wrong list degrades to stale-while-revalidate instead of breaking the page; tools/deploy-check.sh
 * --local fails when the list and index.html disagree.
 */
