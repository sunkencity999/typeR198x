let optPuts = 0;

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await Promise.allSettled(PRECACHE.map(async (url) => {
      try {
        const res = await fetch(url, { credentials: "same-origin" });
        if (cacheable(res)) await cache.put(url, res);
      } catch (_) { /* offline or missing: stale-while-revalidate picks it up on first use */ }
    }));
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keep = new Set([SHELL_CACHE, RUNTIME_CACHE, OPT_CACHE]);
    const names = await caches.keys();
    await Promise.all(names.filter((n) => n.indexOf("typer-") === 0 && !keep.has(n)).map((n) => caches.delete(n)));
  })());
});

self.addEventListener("message", (event) => {
  const d = event.data;
  if (!d || typeof d !== "object") return;
  if (d.type === "SKIP_WAITING") self.skipWaiting();
  else if (d.type === "GET_VERSION" && event.source) event.source.postMessage({ type: "SW_VERSION", version: SW_VERSION });
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  let url;
  try { url = new URL(req.url); } catch (_) { return; }
  if (url.origin !== self.location.origin) return;
  if (url.pathname.indexOf(API_PREFIX) === 0) return;             // the leaderboard API is live data: network only
  if (url.pathname === ROOT_PATH + "sw.js") return;               // never serve ourselves from a cache
  if (req.mode === "navigate") { event.respondWith(navigateFirst(req)); return; }
  if (url.pathname.indexOf("/assets/opt/") !== -1) { event.respondWith(optAsset(req, event)); return; }
  event.respondWith(shellOrRevalidate(req, event));
});

// A response worth storing: a complete same-origin 200 that did not come through a redirect (a redirected
// response served to a later navigation is refused by the browser).
function cacheable(res) {
  return !!res && res.status === 200 && res.type === "basic" && !res.redirected;
}

async function navigateFirst(req) {
  const shell = await caches.open(SHELL_CACHE);
  try {
    const res = await fetch(req);
    if (cacheable(res)) {
      const key = new URL(req.url);
      key.search = "";
      shell.put(key.href, res.clone()).catch(() => {});
    }
    return res;
  } catch (_) {
    return (await shell.match(req, { ignoreSearch: true })) || (await shell.match("./index.html")) || offlineResponse();
  }
}

async function optAsset(req, event) {
  const cache = await caches.open(OPT_CACHE);
  const range = req.headers.get("range");
  if (range) return optRange(cache, req, range, event);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (cacheable(res)) event.waitUntil(storeOpt(cache, req.url, res.clone()));
  return res;
}

// Media (the music transport, range requests): a cached full copy answers any range; "bytes=0-" streams the network
// body to the player and stores the same bytes; other ranges pass through uncached (the Cache API refuses 206s).
async function optRange(cache, req, range, event) {
  const m = /^bytes=(\d*)-(\d*)$/.exec(range);
  const full = m ? await cache.match(req.url) : null;
  if (full) return sliceResponse(full, m);
  if (m && m[1] === "0" && m[2] === "") {
    try {
      const res = await fetch(req.url, { credentials: "same-origin" });
      const len = Number(res.headers.get("content-length"));
      if (res.status !== 200 || !cacheable(res) || !(len > 0) || !res.body || typeof res.body.tee !== "function") return res;
      const [toClient, toCache] = res.body.tee();
      event.waitUntil(storeOpt(cache, req.url, new Response(toCache, { status: 200, headers: new Headers(res.headers) })));
      const h = new Headers(res.headers);
      h.set("Content-Range", "bytes 0-" + (len - 1) + "/" + len);
      h.set("Content-Length", String(len));
      h.set("Accept-Ranges", "bytes");
      return new Response(toClient, { status: 206, statusText: "Partial Content", headers: h });
    } catch (_) { /* fall through to the plain request */ }
  }
  return fetch(req);
}

async function sliceResponse(full, m) {
  const buf = await full.arrayBuffer();
  const total = buf.byteLength;
  const suffix = m[1] === "";
  const start = suffix ? Math.max(0, total - Number(m[2])) : Number(m[1]);
  const end = (suffix || m[2] === "") ? total - 1 : Math.min(total - 1, Number(m[2]));
  if (!(start <= end) || start >= total) return new Response(null, { status: 416, headers: { "Content-Range": "bytes */" + total } });
  const h = new Headers();
  const ct = full.headers.get("content-type");
  if (ct) h.set("Content-Type", ct);
  h.set("Content-Range", "bytes " + start + "-" + end + "/" + total);
  h.set("Content-Length", String(end - start + 1));
  h.set("Accept-Ranges", "bytes");
  return new Response(buf.slice(start, end + 1), { status: 206, statusText: "Partial Content", headers: h });
}

async function storeOpt(cache, key, res) {
  try { await cache.put(key, res); } catch (_) { return; }
  if (++optPuts % OPT_EVICT_EVERY === 0) await evictOpt(cache);
}

// Oldest entries out until the assets/opt cache is under the cap (Cache.keys() lists entries in insertion order).
async function evictOpt(cache) {
  try {
    const keys = await cache.keys();
    const sizes = [];
    let total = 0;
    for (const k of keys) {
      const r = await cache.match(k);
      const n = r ? (Number(r.headers.get("content-length")) || 0) : 0;
      sizes.push([k, n]);
      total += n;
    }
    for (const [k, n] of sizes) {
      if (total <= OPT_CACHE_MAX_BYTES) break;
      await cache.delete(k);
      total -= n;
    }
  } catch (_) { /* best effort */ }
}

async function shellOrRevalidate(req, event) {
  const shell = await caches.open(SHELL_CACHE);
  const pre = await shell.match(req);
  if (pre) return pre;
  const runtime = await caches.open(RUNTIME_CACHE);
  const hit = await runtime.match(req);
  const update = fetch(req).then((res) => {
    if (cacheable(res)) runtime.put(req, res.clone()).catch(() => {});
    return res;
  });
  if (hit) {
    event.waitUntil(update.catch(() => {}));
    return hit;
  }
  try { return await update; } catch (_) { return Response.error(); }
}

function offlineResponse() {
  const html = "<!doctype html><html lang=\"en\"><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">" +
    "<title>Type-R 198X</title><body style=\"margin:0;min-height:100vh;display:grid;place-items:center;background:#0B1030;color:#F6F7FF;font-family:system-ui,sans-serif\">" +
    "<p style=\"padding:2rem;text-align:center\">Type-R 198X is offline and this page is not stored on this device yet.<br>Reconnect and reload.</p></body></html>";
  return new Response(html, { status: 503, headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store" } });
}
