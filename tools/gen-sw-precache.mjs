#!/usr/bin/env node
// tools/gen-sw-precache.mjs [--root <dir>] [--check] [--quiet]
//
// Writes the service worker's precache list (the PRECACHE array between `// @precache-start` and `// @precache-end`
// in sw.js) from what the shell actually references, so the list can never drift from index.html by hand:
//   * every local <script src> and <link href> (stylesheet, preload, manifest, icon, apple-touch-icon) in index.html,
//     with its ?v= token exactly as index.html carries it (tools/bump-version.sh rewrites both in one pass)
//   * "./" and "./index.html" (the navigation fallbacks), the secondary pages, site.webmanifest
//   * assets/fonts/*.woff2 and every file under assets/ui (recursively; og-card.jpg excluded: the social card is
//     never shown in the game)
// The list is sorted after the index.html entries so a run is reproducible. Nothing under assets/opt is precached:
// the loader fetches that art on demand and sw.js keeps it in its own capped cache-first store.
//
// --check   exit 1 when the list in sw.js differs from what this script would write (tools/deploy-check.sh --local)
// --root    repository root (default: the parent of this script's directory)
// Exit 0 on success (or when --check finds no drift), 1 on drift (--check) or a missing sw.js / index.html, 2 on usage.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
let ROOT = path.resolve(HERE, "..");
let CHECK = false;
let QUIET = false;
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === "--root") { ROOT = path.resolve(argv[++i] || ""); }
  else if (a === "--check") CHECK = true;
  else if (a === "--quiet") QUIET = true;
  else if (a === "-h" || a === "--help") { console.log(fs.readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").filter((l) => l.startsWith("//")).map((l) => l.slice(3)).join("\n")); process.exit(0); }
  else { console.error(`unknown argument: ${a}`); process.exit(2); }
}

const indexPath = path.join(ROOT, "index.html");
const swPath = path.join(ROOT, "sw.js");
for (const f of [indexPath, swPath]) {
  if (!fs.existsSync(f)) { console.error(`missing ${f}`); process.exit(1); }
}

export function buildPrecacheList(root) {
  const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
  const fromIndex = [];
  const seen = new Set();
  const add = (u, list) => { if (!seen.has(u)) { seen.add(u); list.push(u); } };
  const tags = html.match(/<(?:script|link)\b[^>]*>/gi) || [];
  for (const t of tags) {
    const m = t.match(/\b(href|src)=["']([^"']*)["']/i);
    if (!m) continue;
    const url = m[2];
    if (/^(https?:)?\/\//i.test(url) || /^(data|mailto|javascript):/i.test(url)) continue;
    if (/^<link/i.test(t)) {
      const rel = (t.match(/\brel=["']([^"']*)["']/i) || [])[1] || "";
      if (!/\b(stylesheet|preload|modulepreload|manifest|icon|apple-touch-icon)\b/i.test(rel)) continue;
    }
    if (/(^|\/)assets\/opt\//.test(url) && !/manifest\.js(\?|$)/.test(url)) continue;   // on-demand art: cache-first in sw.js
    add(url.startsWith("./") || url.startsWith("/") ? url : "./" + url, fromIndex);
  }
  const extra = [];
  add("./", extra);
  add("./index.html", extra);
  for (const page of ["info.html", "support.html", "privacy-policy.html", "privacy.html", "site.webmanifest"]) {
    if (fs.existsSync(path.join(root, page))) add("./" + page, extra);
  }
  const fontsDir = path.join(root, "assets/fonts");
  if (fs.existsSync(fontsDir)) {
    for (const f of fs.readdirSync(fontsDir).sort()) if (/\.woff2$/i.test(f)) add("./assets/fonts/" + f, extra);
  }
  const walk = (dir, rel) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (e.name.startsWith(".")) continue;
      const p = path.join(dir, e.name), r = rel + "/" + e.name;
      if (e.isDirectory()) walk(p, r);
      else if (e.isFile() && e.name !== "og-card.jpg") add("." + r, extra);
    }
  };
  const uiDir = path.join(root, "assets/ui");
  if (fs.existsSync(uiDir)) walk(uiDir, "/assets/ui");
  extra.sort();
  return fromIndex.concat(extra.filter((u) => !fromIndex.includes(u)));
}

export function renderBlock(list) {
  return "// @precache-start (generated by tools/gen-sw-precache.mjs; do not edit by hand)\nconst PRECACHE = [\n" +
    list.map((u) => `  ${JSON.stringify(u)},`).join("\n") + "\n];\n// @precache-end";
}

const BLOCK_RE = /\/\/ @precache-start[^\n]*\nconst PRECACHE = \[[\s\S]*?\];\n\/\/ @precache-end/;

const list = buildPrecacheList(ROOT);
const sw = fs.readFileSync(swPath, "utf8");
if (!BLOCK_RE.test(sw)) { console.error("sw.js has no @precache-start / @precache-end block"); process.exit(1); }
const next = sw.replace(BLOCK_RE, renderBlock(list));
const missing = list.filter((u) => {
  const p = u.replace(/[?#].*$/, "");
  if (p === "./") return false;
  return !fs.existsSync(path.join(ROOT, p.replace(/^\.\//, "")));
});
if (CHECK) {
  const drift = next !== sw;
  if (!QUIET) console.log(`gen-sw-precache: ${list.length} entries${drift ? ", sw.js is STALE (run tools/gen-sw-precache.mjs)" : ", sw.js is current"}${missing.length ? `; missing on disk: ${missing.join(", ")}` : ""}`);
  process.exit(drift || missing.length ? 1 : 0);
}
if (next !== sw) fs.writeFileSync(swPath, next);
if (!QUIET) {
  console.log(`gen-sw-precache: ${list.length} entries written to sw.js${next === sw ? " (no change)" : ""}`);
  if (missing.length) console.log(`  warning: not on disk: ${missing.join(", ")}`);
}
